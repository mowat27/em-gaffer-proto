/**
 * Parity (principle 2, spec 8.7): every capability names its Service method, its routes, its agent tool and its UI
 * control id. UI controls carry the literal attribute data-cap="<id>" (never data-cap={expr}, the test scans source).
 * tests/unit/parity.test.ts enforces the list; layer manifests may add capabilities (LayerManifest.capabilities).
 *
 * Capabilities are added per phase. A capability's `phase` is the phase in which all its columns exist; the test checks
 * every capability with phase <= BUILT_THROUGH_PHASE, and checks UI controls only once BUILT_THROUGH_PHASE >= 3.
 * Every capability has all four columns: there is no per-capability exemption. Chat (send, stop, watch) is
 * infrastructure, not a capability: its routes are in INFRA_ROUTES and its UI carries data-testid, not data-cap.
 * The one exemption is AGENT_ONLY_TOOLS below, which the parity test prints on every run.
 * Data only: the list is the one runtime value in the shared contract files.
 */
import type { ServiceMethod } from "../core/service-api.ts";

export interface RouteRef {
  readonly method: "GET" | "POST";
  readonly path: string;
}

export interface CapabilityTool {
  readonly name: string;
  /** The layer that registers the tool (D8: the registry's tool -> layer map must agree). */
  readonly layer: string;
}

export interface Capability {
  /** Dotted id; also the data-cap value. */
  readonly id: string;
  readonly summary: string;
  readonly phase: number;
  readonly service: ServiceMethod;
  readonly routes: readonly RouteRef[];
  readonly tool: CapabilityTool;
  /** data-cap id (equal to `id`). */
  readonly control: string;
  readonly mutates: boolean;
}

