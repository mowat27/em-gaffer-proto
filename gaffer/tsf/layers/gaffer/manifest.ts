const cap = (name: string, kind: "query" | "action", summary: string, mutates: boolean) => ({
  id: `gaffer.${name}`,
  summary,
  kind,
  handler: name,
  tool: `gaffer_${name}`,
  control: `gaffer.${name}`,
  mutates,
});

const field = (key: string, label: string, kind: "text" | "number" | "toggle" = "text") => ({
  kind,
  label,
  query: "settings",
  field: key,
  action: "set_setting",
  actionInput: { key, value: "$value" },
  capability: "gaffer.set_setting",
});

