// learnings-file: a learnings file is written only by capture-learning (shared:learn), which regenerates it from its
// recorded learnings. Blocks write and edit of one, and bash commands that write and name one, and tells the agent to
// use capture-learning. Always on.
//
// A learnings file is one that starts with HEADER, or one capture-learning wrote (or this gate recognised) in this
// session: the module exports two gates sharing that list, one on tool calls and one that notes each file a successful
// capture-learning call wrote.
import { closeSync, existsSync, openSync, readSync } from "node:fs";
import { relative, resolve } from "node:path";
import { allow, block, defineGate, resolvePath, SHELL_WRITE, shellWriteWords, type Gate } from "../../../engine/gates.ts";

/** First line of every learnings file, as the CLI writes it. */
export const HEADER = "<!-- Generated from the slice-state event log. Record learnings with the learn command; do not edit. -->";

/** True when the file exists and starts with HEADER. Reads only the first bytes. */
export function startsWithHeader(path: string): boolean {
  if (!existsSync(path)) return false;
  let fd: number | undefined;
  try {
    fd = openSync(path, "r");
    const head = Buffer.alloc(HEADER.length);
    const n = readSync(fd, head, 0, HEADER.length, 0);
    return head.subarray(0, n).toString("utf-8") === HEADER;
  } catch {
    return false;
  } finally {
    if (fd !== undefined) closeSync(fd);
  }
}

/** The two gates, with their own list of learnings files (one list per session). */
export function learningsFileGates(): Gate[] {
  const files = new Set<string>(); // absolute paths
  const isLearningsFile = (path: string) => files.has(path) || startsWithHeader(path);
  const refuse = (shown: string, via: string) =>
    block(`${shown} is a learnings file generated by capture-learning. Do not modify it with ${via}. Record each learning with capture-learning (text, topic, file: "${shown}") instead.`, shown);

  const onCall = defineGate({
    tools: ["write", "edit", "bash"],
    check(call, ctx) {
      const shown = (abs: string) => relative(ctx.cwd, abs) || abs;
      if (call.tool === "write" || call.tool === "edit") {
        const path = resolvePath(ctx.cwd, call.input.path);
        if (isLearningsFile(path) || (call.tool === "write" && String(call.input.content ?? "").includes(HEADER))) {
          files.add(path);
          return refuse(shown(path), call.tool);
        }
        return allow();
      }
      const cmd = String(call.input.command ?? "");
      if (!SHELL_WRITE.test(cmd)) return allow();
      for (const path of files) if (cmd.includes(path) || cmd.includes(shown(path))) return refuse(shown(path), "bash");
      // Learnings files on disk this session has not seen yet: any word in the command that names one.
      for (const word of shellWriteWords(cmd) ?? []) {
        const path = resolvePath(ctx.cwd, word);
        if (startsWithHeader(path)) {
          files.add(path);
          return refuse(shown(path), "bash");
        }
      }
      return allow();
    },
  });

  const onResult = defineGate({
    tools: ["capture-learning"],
    on: "tool_result",
    check(call, ctx) {
      if (!call.result?.isError && typeof call.input.file === "string") files.add(resolve(ctx.cwd, call.input.file));
      return allow();
    },
  });

  return [onCall, onResult];
}

export default learningsFileGates();
